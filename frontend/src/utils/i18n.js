export function normalizeLanguage(language) {
  return language === 'Tagalog' || language === 'Filipino' ? 'Tagalog' : 'English'
}

export function translateText(text, language) {
  if (normalizeLanguage(language) !== 'Tagalog') return text
  return TAGALOG_TRANSLATIONS[text] || text
}

export function useTranslation() {
  const [language, setLanguage] = useState(() =>
    normalizeLanguage(window.localStorage.getItem('profile_language') || 'English'),
  )

  useEffect(() => {
    const updateLanguage = () => {
      const currentLanguage = normalizeLanguage(window.localStorage.getItem('profile_language') || 'English')
      setLanguage(currentLanguage)
      document.documentElement.lang = currentLanguage === 'Tagalog' ? 'tl' : 'en'
    }

    updateLanguage()
    window.addEventListener('app-language-change', updateLanguage)
    window.addEventListener('storage', updateLanguage)
    return () => {
      window.removeEventListener('app-language-change', updateLanguage)
      window.removeEventListener('storage', updateLanguage)
    }
  }, [])

  const t = useCallback((text) => translateText(text, language), [language])
  return { language, t }
}
